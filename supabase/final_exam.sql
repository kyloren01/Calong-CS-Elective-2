-- 5. PRODUCT IMAGES (Supabase Storage)
--
-- The bucket is public so the app can show images by their link. Only
-- admins can upload, replace, or delete them.
-- =====================================================================

do $$
begin
  insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  values (
    'product-images', 'product-images', true, 5242880,
    array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
  )
  on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
exception when insufficient_privilege then
  -- Keep everything above. The checklist at the end shows what is missing.
  raise warning 'The image bucket could not be created here.';
end $$;

do $$
begin
  drop policy if exists "product images read" on storage.objects;
  create policy "product images read"
    on storage.objects for select to authenticated
    using (bucket_id = 'product-images');

  drop policy if exists "upload product image" on storage.objects;
  create policy "upload product image"
    on storage.objects for insert to authenticated
    with check (bucket_id = 'product-images' and (select public.is_admin()));

  drop policy if exists "replace product image" on storage.objects;
  create policy "replace product image"
    on storage.objects for update to authenticated
    using (bucket_id = 'product-images' and (select public.is_admin()))
    with check (bucket_id = 'product-images' and (select public.is_admin()));

  drop policy if exists "delete product image" on storage.objects;
  create policy "delete product image"
    on storage.objects for delete to authenticated
    using (bucket_id = 'product-images' and (select public.is_admin()));
exception when insufficient_privilege then
  raise warning 'The image policies could not be created here.';
end $$;


