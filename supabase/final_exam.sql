create table if not exists public.roles (
  id   bigint generated by default as identity primary key,
  role text   not null unique
);

insert into public.roles (role)
values ('customer'), ('admin')
on conflict (role) do nothing;

-- One row per account. Supabase keeps the login itself in auth.users.
create table if not exists public.profiles (
  id         uuid        primary key references auth.users (id) on delete cascade,
  email      text,
  firstname  text,
  lastname   text,
  role_id    bigint      not null references public.roles (id),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id         bigint generated by default as identity primary key,
  name       text        not null unique check (char_length(trim(name)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text           not null check (char_length(trim(name)) > 0),
  description text           not null default '',
  price       numeric(10, 2) not null check (price >= 0),
  created_at  timestamptz    not null default now()
);

-- Columns the final exam adds. On an older products table, this also turns
-- the category text into a link to the categories table.
alter table public.products
  add column if not exists category_id bigint references public.categories (id) on delete restrict;
alter table public.products
  add column if not exists image_path text;

do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'products' and column_name = 'stock'
  ) then
    alter table public.products
      add column stock integer not null default 0 check (stock >= 0);
    -- Sample stock for products that were already here.
    update public.products
    set stock = case name
      when 'Trail Watch' then 0
      when 'Studio Mic'  then 2
      else 5 + (id * 7 % 26)::integer
    end;
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'products' and column_name = 'category'
  ) then
    insert into public.categories (name)
    select distinct coalesce(nullif(trim(category), ''), 'General')
    from public.products
    on conflict (name) do nothing;

    update public.products p
    set category_id = c.id
    from public.categories c
    where p.category_id is null
      and c.name = coalesce(nullif(trim(p.category), ''), 'General');

    alter table public.products drop column category;
  end if;

  -- Every product needs a category, so any that still has none gets "General".
  if exists (select 1 from public.products where category_id is null) then
    insert into public.categories (name) values ('General') on conflict (name) do nothing;
    update public.products
    set category_id = (select id from public.categories where name = 'General')
    where category_id is null;
  end if;
end $$;

alter table public.products alter column category_id set not null;

create table if not exists public.orders (
  id         bigint generated by default as identity primary key,
  user_id    uuid           not null references public.profiles (id) on delete cascade,
  status     text           not null default 'pending'
             check (status in ('pending', 'processing', 'done', 'cancelled')),
  total      numeric(12, 2) not null default 0 check (total >= 0),
  created_at timestamptz    not null default now()
);

-- product_name and unit_price are copies made at checkout, so an old order
-- stays correct when a product is renamed, repriced, or deleted.
create table if not exists public.order_items (
  id           bigint generated by default as identity primary key,
  order_id     bigint         not null references public.orders (id) on delete cascade,
  product_id   bigint         references public.products (id) on delete set null,
  product_name text           not null,
  unit_price   numeric(10, 2) not null check (unit_price >= 0),
  quantity     integer        not null check (quantity > 0)
);

create index if not exists products_price_idx       on public.products (price);
create index if not exists products_category_id_idx on public.products (category_id);
create index if not exists orders_user_id_idx       on public.orders (user_id, created_at desc);
create index if not exists order_items_order_id_idx on public.order_items (order_id);


