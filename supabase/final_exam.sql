-- =====================================================================
-- 7. CHECKLIST (this is the result shown after Run)
-- =====================================================================

select item, found, expected, case when found >= expected then 'OK' else 'MISSING' end as result
from (
  select 1 as position, 'Tables with RLS turned on' as item, 6 as expected,
         (select count(*) from pg_class
          where relnamespace = 'public'::regnamespace and relkind = 'r' and relrowsecurity
            and relname in ('roles', 'profiles', 'categories', 'products', 'orders', 'order_items')) as found
  union all
  select 2, 'Policies on those tables', 14,
         (select count(*) from pg_policies
          where schemaname = 'public'
            and tablename in ('roles', 'profiles', 'categories', 'products', 'orders', 'order_items'))
  union all
  select 3, 'Functions', 4,
         (select count(*) from pg_proc
          where pronamespace = 'public'::regnamespace
            and proname in ('is_admin', 'my_role_id', 'handle_new_user', 'place_order'))
  union all
  select 4, 'Trigger for new accounts', 1,
         (select count(*) from pg_trigger
          where tgname = 'on_auth_user_created' and tgrelid = 'auth.users'::regclass)
  union all
  select 5, 'Image bucket', 1,
         (select count(*) from storage.buckets where id = 'product-images')
  union all
  select 6, 'Image policies', 4,
         (select count(*) from pg_policies
          where schemaname = 'storage' and tablename = 'objects' and policyname like '%product image%')
  union all
  select 7, 'Products', 1, (select count(*) from public.products)
) as checks
order by position;
