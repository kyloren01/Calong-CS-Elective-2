-- Is the signed-in user an admin? "security definer" lets it read profiles
-- without going through the profiles policies, which call it themselves.
create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  return exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.role = 'admin'
  );
end;
$$;

-- The signed-in user's current role. The profiles policy compares against
-- this so that nobody can change their own role.
create or replace function public.my_role_id()
returns bigint
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  return (select p.role_id from public.profiles p where p.id = auth.uid());
end;
$$;

-- Creates the profile for every new account, always as a customer.
-- Email sign-up sends firstname and lastname; Google sends one full name.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  full_name text := trim(coalesce(
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'name',
    ''
  ));
  first_word text := split_part(full_name, ' ', 1);
begin
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'firstname'), ''),
      nullif(first_word, '')
    ),
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'lastname'), ''),
      nullif(trim(substr(full_name, length(first_word) + 1)), '')
    ),
    (select id from public.roles where role = 'customer')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Accounts created before this script get a customer profile too.
insert into public.profiles (id, email, firstname, lastname, role_id)
select
  u.id,
  u.email,
  nullif(trim(u.raw_user_meta_data ->> 'firstname'), ''),
  nullif(trim(u.raw_user_meta_data ->> 'lastname'), ''),
  (select id from public.roles where role = 'customer')
from auth.users u
on conflict (id) do nothing;

-- Checkout. The app sends only product ids and quantities, for example
--   [{"product_id": 3, "quantity": 2}]
-- Names, prices, and stock are read from the products table here. A function
-- runs as one transaction: if any line fails, nothing at all is saved.
create or replace function public.place_order(items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer_id uuid := auth.uid();
  saved_order public.orders%rowtype;
  item        record;
  product     public.products%rowtype;
  order_total numeric(12, 2) := 0;
begin
  if customer_id is null then
    raise exception 'Sign in to place an order.' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = customer_id and r.role = 'customer'
  ) then
    raise exception 'Only customer accounts can place orders.' using errcode = '42501';
  end if;

  if items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then
    raise exception 'Your cart is empty.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(items) as line
    where coalesce(line ->> 'product_id', '') !~ '^[0-9]{1,18}$'
       or coalesce(line ->> 'quantity', '')   !~ '^[1-9][0-9]{0,5}$'
  ) then
    raise exception 'Every item needs a product and a quantity of at least 1.';
  end if;

  insert into public.orders (user_id, status)
  values (customer_id, 'pending')
  returning * into saved_order;

  -- Products are locked in id order, so two checkouts at the same moment
  -- wait for each other instead of selling the same stock twice.
  for item in
    select (line ->> 'product_id')::bigint      as product_id,
           sum((line ->> 'quantity')::integer)  as quantity
    from jsonb_array_elements(items) as line
    group by 1
    order by 1
  loop
    select * into product
    from public.products p
    where p.id = item.product_id
    for update;

    if not found then
      raise exception 'A product in your cart is no longer sold. Please review your cart.';
    end if;

    if product.stock = 0 then
      raise exception '% is out of stock.', product.name;
    end if;

    if product.stock < item.quantity then
      raise exception 'Only % left of %.', product.stock, product.name;
    end if;

    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (saved_order.id, product.id, product.name, product.price, item.quantity);

    update public.products p
    set stock = p.stock - item.quantity
    where p.id = product.id;

    order_total := order_total + product.price * item.quantity;
  end loop;

  update public.orders o
  set total = order_total, status = 'done'
  where o.id = saved_order.id
  returning * into saved_order;

  return jsonb_build_object(
    'id',         saved_order.id,
    'status',     saved_order.status,
    'total',      saved_order.total,
    'created_at', saved_order.created_at,
    'order_items', (
      select jsonb_agg(
        jsonb_build_object(
          'product_name', i.product_name,
          'unit_price',   i.unit_price,
          'quantity',     i.quantity
        )
        order by i.id
      )
      from public.order_items i
      where i.order_id = saved_order.id
    )
  );
end;
$$;


-- =====================================================================
-- 3. WHO MAY USE WHAT (table and function privileges)
--
-- Signed-out visitors (anon) get nothing. Signed-in users (authenticated)
-- get only what a policy below may allow. Column lists matter: nobody can
-- write profiles.role_id or orders.total through the API.
-- =====================================================================

revoke all on public.roles, public.profiles, public.categories,
              public.products, public.orders, public.order_items
  from anon, authenticated;

grant select                         on public.roles       to authenticated;
grant select                         on public.profiles    to authenticated;
grant update (firstname, lastname)   on public.profiles    to authenticated;
grant select, insert, update, delete on public.categories  to authenticated;
grant select, insert, update, delete on public.products    to authenticated;
grant select                         on public.orders      to authenticated;
grant update (status)                on public.orders      to authenticated;
grant select                         on public.order_items to authenticated;

revoke all on function public.is_admin()          from public, anon;
revoke all on function public.my_role_id()        from public, anon;
revoke all on function public.place_order(jsonb)  from public, anon;
revoke all on function public.handle_new_user()   from public, anon, authenticated;

grant execute on function public.is_admin()         to authenticated;
grant execute on function public.my_role_id()       to authenticated;
grant execute on function public.place_order(jsonb) to authenticated;


-- =====================================================================
-- 4. ROW LEVEL SECURITY
--
--  table        signed out  customer                          admin
--  profiles     no access   read + update own row, not role   read all
--  roles        no access   read                              read
--  categories   no access   read                              read, add, edit, delete
--  products     no access   read                              read, add, edit, delete
--  orders       no access   read own                          read all, update status
--  order_items  no access   read items of own orders          read all
-- =====================================================================

alter table public.roles       enable row level security;
alter table public.profiles    enable row level security;
alter table public.categories  enable row level security;
alter table public.products    enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

-- Policies add up, so one forgotten open policy would undo all the others.
-- Remove every old policy on these tables before creating the final ones.
do $$
declare
  old record;
begin
  for old in
    select policyname, tablename
    from pg_policies
    where schemaname = 'public'
      and tablename in ('roles', 'profiles', 'categories', 'products', 'orders', 'order_items')
  loop
    execute format('drop policy %I on public.%I', old.policyname, old.tablename);
  end loop;
end $$;

-- roles
create policy "roles read"
  on public.roles for select to authenticated
  using (true);

-- profiles
create policy "profiles read"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_admin()));

create policy "update own profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()) and not (select public.is_admin()))
  with check (id = (select auth.uid()) and role_id = (select public.my_role_id()));

-- categories
create policy "categories read"
  on public.categories for select to authenticated
  using (true);

create policy "create category"
  on public.categories for insert to authenticated
  with check ((select public.is_admin()));

create policy "update category"
  on public.categories for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "delete category"
  on public.categories for delete to authenticated
  using ((select public.is_admin()));

-- products
create policy "products read"
  on public.products for select to authenticated
  using (true);

create policy "create product"
  on public.products for insert to authenticated
  with check ((select public.is_admin()));

create policy "update product"
  on public.products for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "delete product"
  on public.products for delete to authenticated
  using ((select public.is_admin()));

-- orders: there is no insert policy on purpose. Orders are created only by
-- place_order(), so the app can never save its own prices or totals.
create policy "orders read"
  on public.orders for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

create policy "update order status"
  on public.orders for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- order_items
create policy "order items read"
  on public.order_items for select to authenticated
  using (
    (select public.is_admin())
    or exists (
      select 1
      from public.orders o
      where o.id = order_items.order_id and o.user_id = (select auth.uid())
    )
  );


